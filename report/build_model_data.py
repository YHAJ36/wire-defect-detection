def collect(arm, split='test'):
    src = B2 if 'yolo26' not in arm else B3
    return [r for (run, sp), r in src.items() if run.startswith(arm) and sp == split]

def mean(xs):
    return sum(xs) / len(xs) if xs else None

def arm_summary(arm):
    rs = collect(arm)
    if not rs:
        return None
    d = OrderedDict(n=len(rs))
    for f in ('mAP50', 'mAP50-95', 'P', 'R'):
        vs = [float(r[f]) for r in rs]
        d[f] = OrderedDict(mean=mean(vs), lo=min(vs), hi=max(vs))
    d['runs'] = [r['run'] for r in rs]
    return d

