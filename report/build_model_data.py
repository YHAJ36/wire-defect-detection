def load_eval(fn):
    rows = list(csv.DictReader(open(os.path.join(LOG, fn), encoding='utf-8'), delimiter='\t'))
    last = OrderedDict()
    for r in rows:
        last[(r['run'], r['split'])] = r
    return last

