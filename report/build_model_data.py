# ---------------------------------------------------------------- our data
def vfinal_rows(rows, size, key_idx=(1, 2)):
    out = []
    for r in rows:
        k = r[0]
        ms_i, fps_i = key_idx
        p = PERF[k]
        out.append(OrderedDict(
            model=NAME[k], P=r[1], R=r[2], mAP50=r[3], mAP95=r[4],
            params=p[0], fps=p[fps_i], ms=p[ms_i],
            extra=dict(break_=r[5], thunderbolt=r[6], wear=r[7])))
    return out

